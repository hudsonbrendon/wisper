const DICTS: Record<string, Dict> = {
  en,
  pt,
  es,
  fr,
  de,
  it,
  nl,
  ru,
  pl,
  tr,
  ja,
  ko,
  zh,
  ar,
  hi,
};

/// Right-to-left UI languages (only Arabic is in our set).
const RTL = new Set(["ar"]);

const STORAGE_KEY = "ui_lang";

/// Pick an initial language: a stored choice, else the system language if we
/// translate it, else English.
function initialLang(): string {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && DICTS[stored]) return stored;
  const sys = (navigator.language || "en").slice(0, 2).toLowerCase();
  return DICTS[sys] ? sys : "en";
}

type Translator = (
  key: string,
  vars?: Record<string, string | number>,
) => string;

interface I18nValue {
  lang: string;
  setLang: (l: string) => void;
  t: Translator;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<string>(initialLang);

  // Keep <html lang/dir> in sync so RTL languages render correctly.
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.has(lang) ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: string) => {
    localStorage.setItem(STORAGE_KEY, l);
    setLangState(l);
  }, []);

  const t = useCallback<Translator>(
    (key, vars) => {
      const dict = DICTS[lang] ?? en;
      let s = dict[key] ?? en[key] ?? key;
      if (vars) {
        for (const k of Object.keys(vars)) {
          s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
        }
      }
      return s;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
